function buildAnalysis(question: string, base: AnalysisTemplate): LegalAnalysis {
  return {
    ...base,
    id: crypto.randomUUID(),
    question,
    createdAt: new Date().toISOString(),
  };
}

function localAnalyzeSituation(question: string): LegalAnalysis {
  const normalized = question.toLowerCase();
  const match = rules.find((rule) => rule.words.some((word) => normalized.includes(word)));
  return buildAnalysis(question, match?.result ?? fallbackAnalysis);
}

function isLegalCategory(value: unknown): value is LegalCategory {
  return typeof value === 'string' && legalCategories.includes(value as LegalCategory);
}

function readStringArray(value: unknown) {
  return Array.isArray(value)
    ? value.filter((item): item is string => typeof item === 'string' && item.trim().length > 0).slice(0, 5)
    : [];
}

function parseAiText(text: string): AiAnalysis | null {
  const cleaned = text.replace(/^```(?:json)?/i, '').replace(/```$/i, '').trim();
  try {
    const parsed: unknown = JSON.parse(cleaned);
    return parsed && typeof parsed === 'object' ? parsed as AiAnalysis : null;
  } catch {
    return null;
  }
}

function normalizeAiAnalysis(question: string, ai: AiAnalysis): LegalAnalysis | null {
  const rights = readStringArray(ai.rights);
  const steps = readStringArray(ai.steps);

  if (
    typeof ai.title !== 'string'
    || typeof ai.summary !== 'string'
    || typeof ai.meaning !== 'string'
    || !isLegalCategory(ai.category)
    || rights.length < 2
    || steps.length < 2
  ) {
    return null;
  }

  return buildAnalysis(question, {
    title: ai.title,
    category: ai.category,
    summary: ai.summary,
    meaning: ai.meaning,
    rights,
    steps,
  });
}

export async function analyzeSituation(question: string): Promise<LegalAnalysis> {
  if (!isSupabaseConfigured) return localAnalyzeSituation(question);

  try {
    const { data, error } = await supabase.functions.invoke('ai', {
      body: {
        prompt: question,
        system: legalAssistantSystemPrompt,
      },
    });

    if (error) return localAnalyzeSituation(question);

    const text = typeof data === 'object' && data && 'text' in data ? data.text : null;
    if (typeof text !== 'string') return localAnalyzeSituation(question);

    const parsed = parseAiText(text);
    return parsed ? normalizeAiAnalysis(question, parsed) ?? localAnalyzeSituation(question) : localAnalyzeSituation(question);
  } catch {
    return localAnalyzeSituation(question);
  }
}

export function loadHistory(): LegalAnalysis[] {
  const raw = localStorage.getItem(historyKey);
  if (!raw) return [];

  try {
    const value: unknown = JSON.parse(raw);
    return Array.isArray(value) ? (value as LegalAnalysis[]) : [];
  } catch {
    return [];
  }
}

export function saveAnalysis(item: LegalAnalysis) {
  const next = [item, ...loadHistory()].slice(0, 12);
  localStorage.setItem(historyKey, JSON.stringify(next));
}

export function findAnalysis(id: string) {
  return loadHistory().find((item) => item.id === id);
}
