export function analyzeSituation(question: string): LegalAnalysis {
  const normalized = question.toLowerCase();
  const match = rules.find((rule) => rule.words.some((word) => normalized.includes(word)));
  const base = match?.result ?? fallbackAnalysis;

  return {
    ...base,
    id: crypto.randomUUID(),
    question,
    createdAt: new Date().toISOString(),
  };
}

export function loadHistory(): LegalAnalysis[] {
  const raw = localStorage.getItem(historyKey);
  if (!raw) return [];

  try {
    const value: unknown = JSON.parse(raw);
    return Array.isArray(value) ? (value as LegalAnalysis[]) : [];
  } catch {
    return [];
  }
}

export function saveAnalysis(item: LegalAnalysis) {
  const next = [item, ...loadHistory()].slice(0, 12);
  localStorage.setItem(historyKey, JSON.stringify(next));
}

export function findAnalysis(id: string) {
  return loadHistory().find((item) => item.id === id);
}

