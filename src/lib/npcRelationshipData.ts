const relationshipProfileMap: Record<string, NpcRelationshipProfile> = npcRelationshipProfiles;

export function getRelationshipStage(score: number): RelationshipStage {
  if (score >= 6) return 'trusted';
  if (score >= 2) return 'friendly';
  return 'stranger';
}

export function getNpcIntroLines(npcId: string, score: number, completedBefore: boolean, playerName: string) {
  const profile = relationshipProfileMap[npcId];
  if (!profile) return [];
  const lines = personalizeLines(profile.intro[getRelationshipStage(score)], playerName);
  if (!completedBefore) return lines;

  return [
    ...lines,
    line(`${npcId}-memory`, playerName, 'Мы уже разбирали похожую ситуацию. Посмотрим, что изменилось сейчас.', 'neutral'),
  ];
}

export function getNpcCaseReaction(npcId: string, percent: number) {
  const profile = relationshipProfileMap[npcId];
  if (!profile) return '';
  if (percent >= 80) return profile.success;
  if (percent >= 50) return profile.mixed;
  return profile.fail;
}

export function getNpcCaseReactionLines(npcId: string, npcName: string, percent: number, playerName: string) {
  const npcReaction = getNpcCaseReaction(npcId, percent);
  if (!npcReaction) return [];

  const heroText = percent >= 80
    ? 'Ты сам всё понял. Я только помог разложить это по шагам.'
    : percent >= 50
      ? 'Да, тут есть ошибки, но теперь понятно, где именно дело может просесть.'
      : 'Ошибиться в кейсе лучше, чем в жизни. Давай запомним, почему этот путь опасный.';

  return [
    line(`${npcId}-case-reaction`, npcName, npcReaction, percent >= 80 ? 'happy' : 'worried'),
    line(`${npcId}-hero-reaction`, playerName, heroText, 'neutral'),
  ];
}

function line(id: string, speaker: string, text: string, emotion: DialogueLine['emotion']): DialogueLine {
  return { id, speaker, text, emotion };
}

function personalizeLines(lines: DialogueLine[], playerName: string) {
  let greeted = false;

  return lines.map((item) => {
    if (item.speaker === 'ГГ') {
      return { ...item, speaker: playerName };
    }

    if (!greeted) {
      greeted = true;
      return { ...item, text: `Привет, ${playerName}. ${item.text}` };
    }

    return item;
  });
}
